#!/bin/sh
# FlossWare secondary DNS zone sync - regenerates /etc/dnsmasq.conf on util-ap
# from admin-ap's live generated config, then restarts dnsmasq if changed.
# Source of truth: admin-ap (192.168.1.2). Run weekly via cron + on demand.

set -e
CONF=/etc/dnsmasq.conf
TMP=$(mktemp)
ZONE=$(mktemp)
trap 'rm -f "$TMP" "$ZONE"' EXIT

ssh -o BatchMode=yes -o ConnectTimeout=10 admin-ap \
    "grep -vE '^[[:space:]]*#|^[[:space:]]*$' /tmp/dnsmasq/dnsmasq.conf" > "$TMP" \
    || { echo "$(date): fetch from admin-ap failed" >> /var/log/dns-sync.log; exit 1; }

grep -E '^(host-record|cname|address|ptr-record|dhcp-host)=' "$TMP" > "$ZONE"
[ -s "$ZONE" ] || { echo "$(date): no zone records found, aborting" >> /var/log/dns-sync.log; exit 1; }

{
    echo "# FlossWare secondary DNS - util-ap chroot (192.168.1.3)"
    echo "# AUTO-GENERATED by sync-dns-zone.sh from admin-ap - do not hand-edit zone below"
    echo "# Last synced: $(date)"
    echo "port=53"
    echo "listen-address=192.168.1.3"
    echo "bind-interfaces"
    echo "no-hosts"
    echo "no-resolv"
    echo "domain=flossware.com"
    echo "local=/flossware.com/"
    echo "localise-queries"
    echo "bogus-priv"
    echo "domain-needed"
    echo "stop-dns-rebind"
    echo "cache-size=3000"
    echo "dns-forward-max=200"
    echo "log-async"
    grep -E '^server=' "$TMP" | head -4
    echo ""
    echo "# ---- zone (synced from admin-ap) ----"
    cat "$ZONE"
} > "$CONF.new"

if cmp -s "$CONF.new" "$CONF"; then
    rm -f "$CONF.new"
    echo "$(date): zone unchanged" >> /var/log/dns-sync.log
else
    [ -f "$CONF" ] && cp "$CONF" "$CONF.bak"
    mv "$CONF.new" "$CONF"
    /etc/init.d/dnsmasq restart >/dev/null 2>&1 || /etc/init.d/dnsmasq start >/dev/null 2>&1
    echo "$(date): zone updated, dnsmasq restarted" >> /var/log/dns-sync.log
fi
